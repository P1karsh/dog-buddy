// Builds dev/sprites.html: a self-contained preview of every animation.
// Everything (player code, animation data, sprite sheets) is embedded, so the page
// works when opened straight from disk, in an app preview, or from a server.

const STYLE = `
  body { margin: 0; padding: 16px; background: #f4efe6; font: 13px/1.4 ui-rounded, "Segoe UI", system-ui, sans-serif; color: #3b2a1a; }
  h1 { font-size: 16px; margin: 0 0 10px; }
  .bar { display: flex; gap: 6px; flex-wrap: wrap; margin-bottom: 12px; align-items: center; }
  button { font: inherit; padding: 4px 10px; border-radius: 8px; border: 1px solid #e0cfb4; background: #fff; color: inherit; cursor: pointer; }
  button[aria-pressed="true"] { background: #ffe2bd; border-color: #e08a3c; }
  .grid { display: flex; flex-wrap: wrap; gap: 8px; }
  .cell { background: #fff; border: 1px solid #eadfcd; border-radius: 10px; padding: 4px 4px 2px; text-align: center; }
  .cell small { display: block; color: #8a7360; }
  .cell canvas { display: block; image-rendering: pixelated; }
  .err { color: #c0392b; }
  body.dark { background: #2a2420; color: #eee; }
  body.dark .cell { background: #3a322c; border-color: #4a4038; }
  body.dark button { background: #3a322c; border-color: #4a4038; }
`;

const APP = `
  DogSprites.setLoader((id) => new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error('could not decode ' + id));
    img.src = 'data:image/png;base64,' + SHEETS[id];
  }));
  const variants = [['golden'], ['bernese'], ['lab', 'yellow'], ['lab', 'black'], ['lab', 'chocolate']];
  let current = variants[0];
  let dogs = [];
  let left = false;
  function show() {
    dogs.forEach((d) => d.destroy());
    dogs = [];
    const grid = document.getElementById('grid');
    grid.replaceChildren();
    for (const [name, a] of Object.entries(DogSprites.META.anims)) {
      const cell = document.createElement('div');
      cell.className = 'cell';
      const cap = document.createElement('small');
      cap.textContent = name + (a.loop ? ' (loop)' : '');
      const d = DogSprites.create(current[0], current[1], { scale: 3 });
      if (a.loop) d.loop(name);
      else {
        d.loop('sit');
        const again = () => { if (dogs.includes(d)) d.play(name).then(() => setTimeout(again, 700)); };
        d.ready.then(again);
      }
      d.ready.catch((e) => { cap.textContent = name + ': ' + e.message; cap.className = 'err'; });
      d.facing(left ? 'left' : 'right');
      cell.append(d.el, cap);
      grid.append(cell);
      dogs.push(d);
    }
    document.querySelectorAll('#breeds button').forEach((b) => b.setAttribute('aria-pressed', String(b.textContent === current.join(' '))));
  }
  for (const v of variants) {
    const b = document.createElement('button');
    b.textContent = v.join(' ');
    b.onclick = () => { current = v; show(); };
    document.getElementById('breeds').append(b);
  }
  document.getElementById('dark').onclick = () => document.body.classList.toggle('dark');
  document.getElementById('flip').onclick = () => { left = !left; dogs.forEach((d) => d.facing(left ? 'left' : 'right')); };
  show();
`;

// Inline <script> bodies must not contain a closing script tag.
const safe = (js) => js.replace(/<\/script/gi, '<\\/script');

export function previewPage({ meta, player, sheets }) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Sprite Preview</title>
<!-- Generated by tools/sprites/build.mjs. Open it directly; no server needed. -->
<style>${STYLE}</style>
</head>
<body>
<h1>Dog Buddy: sprite preview (dev only)</h1>
<div class="bar" id="breeds"></div>
<div class="bar"><button id="dark">dark bg</button><button id="flip">face left</button></div>
<div class="grid" id="grid"></div>
<script>globalThis.DogSpriteMeta = ${JSON.stringify(meta)};</script>
<script>${safe(player)}</script>
<script>const SHEETS = ${JSON.stringify(sheets)};</script>
<script>${safe(APP)}</script>
</body>
</html>
`;
}
